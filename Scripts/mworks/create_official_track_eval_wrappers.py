"""Generate controller-connected evaluation wrappers for official UGV tracks.

The official ``Models/UGV/saidao`` track files are kept read-only by project
policy. They provide track geometry but omit the obstacle-avoidance controller
instance and the controller-to-allocation connections. This helper creates
reviewable wrappers under ``Models/UGV/Test`` so M6 can evaluate the same
controller against those track geometries without editing the official source
files.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re


PROJECT_ROOT = Path(__file__).resolve().parents[2]
UGV_ROOT = PROJECT_ROOT / "Models" / "UGV"
SAIDAO_ROOT = UGV_ROOT / "saidao"
TEST_ROOT = UGV_ROOT / "Test"


CONTROLLER_DECL = """  Control.ObstacleAvoidanceController.ObsAvoidController_Sysblock2 obsAvoidController_Sysblock
    "避障算法模型，用于控制小车遇到障碍或道路边缘时的运动决策" annotation(Placement(transformation(origin = {-141, -45.23},
    extent = {{-27, -27}, {27, 27}})), __MWORKS(SECInstance = true));
"""


CONTROLLER_CONNECTIONS = """  connect(obsAvoidController_Sysblock.front_dist, distanceSensor1.front_dist);
  connect(obsAvoidController_Sysblock.rear_dist, distanceSensor1.rear_dist);
  connect(obsAvoidController_Sysblock.left_dist, distanceSensor1.left_dist);
  connect(obsAvoidController_Sysblock.right_dist, distanceSensor1.right_dist);
  connect(obsAvoidController_Sysblock.speed, ctrlAlloc.speed_oa);
  connect(obsAvoidController_Sysblock.steer, ctrlAlloc.steer_oa);
"""


DIAGNOSTIC_NEAREST_OBSTACLE_CONNECTIONS = """  connect(obsAvoidController_Sysblock.front_dist, distanceSensor1.DisObstacle);
  connect(obsAvoidController_Sysblock.rear_dist, distanceSensor1.rear_dist);
  connect(obsAvoidController_Sysblock.left_dist, distanceSensor1.left_dist);
  connect(obsAvoidController_Sysblock.right_dist, distanceSensor1.right_dist);
  connect(obsAvoidController_Sysblock.speed, ctrlAlloc.speed_oa);
  connect(obsAvoidController_Sysblock.steer, ctrlAlloc.steer_oa);
"""


def generate_wrapper(track_index: int, diagnostic_nearest_obstacle: bool = False) -> Path:
    source_name = f"saidao{track_index}"
    target_name = (
        f"Saidao{track_index}NearestObstacleDiag"
        if diagnostic_nearest_obstacle
        else f"Saidao{track_index}Eval"
    )
    source = SAIDAO_ROOT / f"{source_name}.mo"
    target = TEST_ROOT / f"{target_name}.mo"
    text = source.read_text(encoding="utf-8")

    text = re.sub(
        rf"^model {source_name}\b",
        f"model {target_name}",
        text,
        count=1,
        flags=re.MULTILINE,
    )
    text = re.sub(
        rf"^\s*end {source_name};\s*$",
        f"  end {target_name};",
        text,
        count=1,
        flags=re.MULTILINE,
    )

    if "ObsAvoidController_Sysblock2" not in text:
        marker = "  Control.ControlAllocate.CtrlAlloc ctrlAlloc"
        text = text.replace(marker, CONTROLLER_DECL + marker, 1)

    if "connect(obsAvoidController_Sysblock.speed, ctrlAlloc.speed_oa)" not in text:
        marker = "  connect(ctrlAlloc.speed, pID_Ackermann.v_desired)"
        connections = (
            DIAGNOSTIC_NEAREST_OBSTACLE_CONNECTIONS
            if diagnostic_nearest_obstacle
            else CONTROLLER_CONNECTIONS
        )
        text = text.replace(marker, connections + marker, 1)

    header = (
        f"// Generated by Scripts/mworks/create_official_track_eval_wrappers.py.\n"
        f"// Source geometry: Models/UGV/saidao/{source_name}.mo.\n"
        f"// Do not edit official saidao source files for M6 evaluation.\n"
    )
    if diagnostic_nearest_obstacle:
        header += (
            "// Diagnostic only: front_dist is connected to distanceSensor1.DisObstacle\n"
            "// to test nearest-obstacle input semantics. Do not claim this as\n"
            "// final competition evidence without interface review.\n"
        )
    normalized_text = "\n".join(line.rstrip() for line in text.splitlines()) + "\n"
    target.write_text(header + normalized_text, encoding="utf-8", newline="\n")
    return target


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--diagnostic-nearest-obstacle-track",
        type=int,
        choices=range(1, 5),
        metavar="{1,2,3,4}",
        help="Generate one diagnostic wrapper that feeds DisObstacle into controller front_dist.",
    )
    args = parser.parse_args()

    TEST_ROOT.mkdir(parents=True, exist_ok=True)
    if args.diagnostic_nearest_obstacle_track:
        generated = [
            generate_wrapper(
                args.diagnostic_nearest_obstacle_track,
                diagnostic_nearest_obstacle=True,
            )
        ]
    else:
        generated = [generate_wrapper(index) for index in range(1, 5)]
    for path in generated:
        print(path.relative_to(PROJECT_ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
